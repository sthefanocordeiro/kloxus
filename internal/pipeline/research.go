package pipeline

// Shared per-story research (KLOX-67 §7.2): one Haiku call per story —
// summary, sourced facts, open questions and the AI pauta draft body —
// cached in story_research under a content key so every newsletter that
// picks the story reuses the same payload. The cache is what makes the
// paid action "once per story", not once per newsletter per story.
import (
	"context"
	"crypto/sha256"
	"database/sql"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"log/slog"
	"sort"
	"strings"

	"github.com/sthefanocordeiro/kloxus/internal/dedupe"
	"github.com/sthefanocordeiro/kloxus/internal/llm"
	"github.com/sthefanocordeiro/kloxus/internal/store"
	"github.com/sthefanocordeiro/kloxus/internal/strutil"
)

// researchSourceExcerpt bounds each source inside the research prompt —
// the §7.2 "at most three sources, each at most 1,200 characters" rule.
const researchSourceExcerpt = 1200
const researchMaxSources = 3

// Research is the cached per-story payload. It doubles as the item's
// dossier (Fontes e fatos) and carries the AI pauta draft body.
type Research struct {
	Title         string          `json:"title"`
	Summary       string          `json:"summary"`
	Facts         []DossierFact   `json:"facts"`
	OpenQuestions []string        `json:"open_questions"`
	DraftBody     string          `json:"draft_body"`
	Sources       []DossierSource `json:"sources"`
	Model         string          `json:"model,omitempty"`
}

// researchAnswer is the model's JSON reply shape.
type researchAnswer struct {
	Summary       string          `json:"summary"`
	Facts         []DossierFact   `json:"facts"`
	OpenQuestions []string        `json:"open_questions"`
	DraftBody     string          `json:"draft_body"`
	Sources       []DossierSource `json:"sources"`
}

// ResearchKey is the story's content identity for the shared cache:
// the sorted canonical URLs of its evidence items. Two newsletters
// selecting the same story produce the same key.
func ResearchKey(items []store.Item) string {
	keys := []string{}
	for _, it := range items {
		if it.Signal() {
			continue
		}
		u := it.CanonicalURL
		if u == "" {
			u = dedupe.Canonical(it.URL)
		}
		if u == "" {
			u = fmt.Sprint(it.ID)
		}
		keys = append(keys, u)
	}
	sort.Strings(keys)
	sum := sha256.Sum256([]byte(strings.Join(keys, "\n")))
	return hex.EncodeToString(sum[:16])
}

// Researcher generates and caches per-story research.
type Researcher struct {
	Pool  *store.Pool
	LLM   llm.Provider
	Model string
	// PaidActionsPerDay bounds one workspace's paid actions per UTC day
	// (§7.3: ≤5). 0 disables the cap.
	PaidActionsPerDay int
}

// researchOutcome says where the answer came from.
type researchOutcome int

const (
	researchFresh    researchOutcome = iota // generated now (paid call)
	researchCached                          // shared cache hit (free)
	researchDegraded                        // cap/failure — no research served
)

// ForStory returns the story's research — from the shared cache when
// present, generated by one Haiku call otherwise. On kill switch, daily
// cap, per-workspace paid-action cap or API failure it returns no
// research (researchDegraded) and a nil error: degradation is absence,
// not an error path — the caller falls back to the deterministic
// dossier, so no "unavailable" placeholder ever renders (owner D4).
func (rc *Researcher) ForStory(ctx context.Context, ws *store.DB, story *store.Story) (*Research, researchOutcome, error) {
	items := evidenceItems(story.Items)
	key := ResearchKey(items)
	if rc.Pool != nil {
		if cached, err := rc.Pool.ResearchGet(ctx, key); err == nil {
			var r Research
			if json.Unmarshal([]byte(cached.JSON), &r) == nil {
				return &r, researchCached, nil
			}
		} else if err != sql.ErrNoRows {
			return nil, 0, err
		}
	}
	if rc.LLM == nil || rc.Model == "" {
		return nil, researchDegraded, nil
	}
	if rc.PaidActionsPerDay > 0 && ws != nil {
		if n, err := ws.PaidActionsToday(ctx); err == nil && n >= rc.PaidActionsPerDay {
			return nil, researchDegraded, nil
		}
	}
	r, err := rc.generate(ctx, story, items)
	if err != nil {
		if b, ok := llm.AsBlocked(err); ok {
			slog.Info("research blocked", "reason", b.Reason)
		} else {
			slog.Warn("research failed", "err", err)
		}
		return nil, researchDegraded, nil
	}
	if rc.Pool != nil {
		data, _ := json.Marshal(r)
		if err := rc.Pool.ResearchSave(ctx, key, string(data), rc.Model); err != nil {
			slog.Warn("research cache save failed", "err", err)
		}
	}
	if ws != nil {
		if err := ws.RecordPaidAction(ctx, store.PaidActionResearch, story.ID); err != nil {
			slog.Warn("paid-action record failed", "err", err)
		}
	}
	return r, researchFresh, nil
}

// generate renders the research prompt over ≤3 sources × 1,200 chars
// and parses the answer into a Research with resolved source refs.
func (rc *Researcher) generate(ctx context.Context, story *store.Story, items []store.Item) (*Research, error) {
	srcs := items
	if len(srcs) > researchMaxSources {
		srcs = srcs[:researchMaxSources]
	}
	type src struct {
		Ref  int
		URL  string
		Name string
		Text string
	}
	data := struct {
		Title   string
		Sources []src
	}{Title: story.Title}
	for i, it := range srcs {
		data.Sources = append(data.Sources, src{
			Ref: i + 1, URL: it.URL, Name: it.SourceName,
			Text: strutil.Truncate(it.ContentText, researchSourceExcerpt),
		})
	}
	user, err := RenderPrompt("research", data)
	if err != nil {
		return nil, err
	}
	req := llm.Request{Model: rc.Model, Template: "research", User: user, MaxTokens: 4096}
	if err := llm.CheckSize(req); err != nil {
		return nil, err
	}
	resp, err := rc.LLM.Complete(ctx, req)
	if err != nil {
		return nil, err
	}
	var ans researchAnswer
	if err := decodeJSON(resp.Text, &ans); err != nil {
		return nil, fmt.Errorf("research: %w", err)
	}
	r := &Research{
		Title:         story.Title,
		Summary:       strings.TrimSpace(ans.Summary),
		Facts:         ans.Facts,
		OpenQuestions: ans.OpenQuestions,
		DraftBody:     strings.TrimSpace(ans.DraftBody),
		Model:         rc.Model,
	}
	if r.Facts == nil {
		r.Facts = []DossierFact{}
	}
	if r.OpenQuestions == nil {
		r.OpenQuestions = []string{}
	}
	// Clamp to the §7.2 shape: 3–5 facts, refs pointing at real sources.
	if len(r.Facts) > 5 {
		r.Facts = r.Facts[:5]
	}
	valid := map[int]bool{}
	for _, s := range data.Sources {
		valid[s.Ref] = true
	}
	for _, s := range ans.Sources {
		if valid[s.Ref] {
			r.Sources = append(r.Sources, s)
		}
	}
	if len(r.Sources) == 0 {
		for _, s := range data.Sources {
			r.Sources = append(r.Sources, DossierSource{Ref: s.Ref, URL: s.URL, Name: s.Name})
		}
	}
	// Attach item ids so the issue document resolves [n] citations.
	for i := range r.Sources {
		for j, it := range srcs {
			if j+1 == r.Sources[i].Ref {
				r.Sources[i].ItemID = it.ID
				if r.Sources[i].Name == "" {
					r.Sources[i].Name = it.SourceName
				}
				if r.Sources[i].URL == "" {
					r.Sources[i].URL = it.URL
				}
			}
		}
	}
	return r, nil
}

// ToDossier shapes the research payload as the item dossier the
// "Fontes e fatos" surface and the issue document already consume.
func (r *Research) ToDossier(ref int) *Dossier {
	return &Dossier{
		Ref: ref, Title: r.Title, Origin: "research",
		Summary: r.Summary, Facts: r.Facts,
		Unknowns: r.OpenQuestions, Sources: r.Sources,
		Interpretation: []string{},
	}
}
