package web

// Email-safe HTML for the daily Radar briefing (KLOX-267), implementing
// docs/design/radar-email.{pt,en}.html from KLOX-251: tables and inline
// CSS only, no external assets, no author-commentary block, and one
// teal "create a post" CTA per story.

import (
	"fmt"
	"html"
	"strings"
	"time"
)

type pautaMailStory struct {
	Card    pautaCardView
	PostURL string
}

const mailFont = "-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif"

func mailEscape(s string) string { return html.EscapeString(s) }

func safeMailURL(u string) string {
	if strings.HasPrefix(u, "https://") || strings.HasPrefix(u, "http://") {
		return u
	}
	return ""
}

func mailLangPT(lang string) bool { return lang != "en" }

func mailDate(day, lang string) string {
	t, err := time.Parse("2006-01-02", day)
	if err != nil {
		return day
	}
	if mailLangPT(lang) {
		weekdays := []string{"domingo", "segunda-feira", "terça-feira", "quarta-feira", "quinta-feira", "sexta-feira", "sábado"}
		months := []string{"janeiro", "fevereiro", "março", "abril", "maio", "junho", "julho", "agosto", "setembro", "outubro", "novembro", "dezembro"}
		return fmt.Sprintf("%s, %d de %s de %d", weekdays[int(t.Weekday())], t.Day(), months[int(t.Month())-1], t.Year())
	}
	return t.Format("Monday, January 2, 2006")
}

func mailTitleDate(day, lang string) string {
	t, err := time.Parse("2006-01-02", day)
	if err != nil {
		return day
	}
	if mailLangPT(lang) {
		return t.Format("02/01/2006")
	}
	return t.Format("Jan 2, 2006")
}

func mailAge(c pautaCardView, lang string) string {
	if c.AgeHours == nil {
		return ""
	}
	n := int(*c.AgeHours + 0.5)
	if n < 1 {
		if mailLangPT(lang) {
			return "agora"
		}
		return "just now"
	}
	if mailLangPT(lang) {
		return fmt.Sprintf("há %d h", n)
	}
	return fmt.Sprintf("%d h ago", n)
}

func mailCount(n int, lang string) string {
	if mailLangPT(lang) {
		if n == 1 {
			return "1 notícia"
		}
		return fmt.Sprintf("%d notícias", n)
	}
	if n == 1 {
		return "1 story"
	}
	return fmt.Sprintf("%d stories", n)
}

// renderPautaMailHTML renders the fixed part of the KLOX-251 template
// with live card data. Everything dynamic is HTML-escaped; external
// story links are limited to http(s). The composite links (/claim and
// /daily-mail/unsub) are generated by the server and escaped here too.
func renderPautaMailHTML(lang, day, pubName string, stories []pautaMailStory, appURL, unsubURL string) string {
	pt := mailLangPT(lang)
	esc := mailEscape
	count := mailCount(len(stories), lang)
	title := "Your Radar today"
	intro := "What moved across your sources in the last 24 hours, already filtered by your topics and beat categories."
	cta := "Create a post with this story →"
	footerBecause := "You receive this email because you follow the <strong>%s</strong> Radar in Kloxus."
	openLabel := "Open in Kloxus"
	unsubLabel := "Unsubscribe from this Radar"
	tagline := "Kloxus · your AI-assisted newsroom, with sources and human decisions."
	preheader := fmt.Sprintf("%s from your Radar today. Pick one and turn it into a post in Kloxus.", count)
	htmlLang := "en"
	if pt {
		htmlLang = "pt-BR"
		title = "Seu Radar de hoje"
		intro = "O que movimentou suas fontes nas últimas 24 horas, já filtrado pelos seus temas e editorias."
		cta = "Criar post com essa notícia →"
		footerBecause = "Você recebe este e-mail porque segue o Radar <strong>%s</strong> no Kloxus."
		openLabel = "Abrir no Kloxus"
		unsubLabel = "Descadastrar deste Radar"
		tagline = "Kloxus · sua redação assistida por IA, com fontes e decisão humana."
		preheader = fmt.Sprintf("%s do seu Radar hoje. Escolha uma e vire post no Kloxus.", count)
	}

	var b strings.Builder
	fmt.Fprintf(&b, `<!DOCTYPE html>
<html lang="%s" xmlns="http://www.w3.org/1999/xhtml">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="X-UA-Compatible" content="IE=edge">
<title>Kloxus — Radar: %s — %s</title>
</head>
<body style="margin:0;padding:0;background-color:#faf8f3;">
<div style="display:none;max-height:0;overflow:hidden;mso-hide:all;">%s</div>
<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0" style="background-color:#faf8f3;">
<tr><td align="center" style="padding:24px 12px;">
<!--[if mso]><table role="presentation" width="600" cellpadding="0" cellspacing="0" border="0"><tr><td><![endif]-->
<table role="presentation" width="600" cellpadding="0" cellspacing="0" border="0" style="width:100%%;max-width:600px;background-color:#fffef9;border:1px solid #e3ddd0;border-radius:12px;">
<tr><td style="padding:24px 28px 20px;">
<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"><tr>
<td style="font-family:%s;font-size:20px;font-weight:800;letter-spacing:-0.5px;color:#172033;">Kloxus<span style="color:#0f766e;">.</span></td>
<td align="right" style="font-family:%s;"><span style="display:inline-block;background-color:#e6f4f2;color:#0f766e;font-size:11px;font-weight:700;letter-spacing:1.5px;text-transform:uppercase;padding:5px 10px;border-radius:999px;">Radar</span></td>
</tr></table>
</td></tr>
<tr><td style="padding:0 28px 6px;">
<p style="margin:0;font-family:%s;font-size:24px;line-height:30px;font-weight:800;letter-spacing:-0.5px;color:#172033;">%s</p>
<p style="margin:6px 0 0;font-family:%s;font-size:13px;line-height:19px;color:#556070;">%s &middot; %s &middot; %s</p>
</td></tr>
<tr><td style="padding:10px 28px 8px;"><p style="margin:0;font-family:%s;font-size:14px;line-height:21px;color:#556070;">%s</p></td></tr>`,
		htmlLang, esc(pubName), esc(mailTitleDate(day, lang)), esc(preheader), mailFont, mailFont, mailFont, esc(title), mailFont,
		esc(pubName), esc(mailDate(day, lang)), esc(count), mailFont, esc(intro))

	for _, st := range stories {
		c := st.Card
		storyURL := safeMailURL(c.URL)
		titleHTML := esc(c.Title)
		if storyURL != "" {
			titleHTML = fmt.Sprintf(`<a href="%s" style="color:#172033;text-decoration:none;">%s</a>`, esc(storyURL), titleHTML)
		}
		meta := esc(c.Outlet)
		if age := mailAge(c, lang); age != "" {
			if meta != "" {
				meta += " &middot; "
			}
			meta += esc(age)
		}
		fmt.Fprintf(&b, `
<tr><td style="padding:14px 28px;border-top:1px solid #e3ddd0;">
<p style="margin:0 0 4px;font-family:%s;font-size:11px;line-height:15px;font-weight:700;letter-spacing:1.2px;text-transform:uppercase;color:#556070;">%s</p>
<p style="margin:0 0 6px;font-family:%s;font-size:16px;line-height:22px;font-weight:700;">%s</p>`,
			mailFont, meta, mailFont, titleHTML)
		if strings.TrimSpace(c.Summary) != "" {
			fmt.Fprintf(&b, `
<p style="margin:0;font-family:%s;font-size:14px;line-height:21px;color:#556070;">%s</p>`, mailFont, esc(c.Summary))
		}
		fmt.Fprintf(&b, `
<p style="margin:12px 0 0;"><a href="%s" style="display:inline-block;background-color:#0f766e;color:#ffffff;font-family:%s;font-size:13px;font-weight:700;line-height:18px;padding:9px 14px;border-radius:8px;text-decoration:none;">%s</a></p>
</td></tr>`, esc(st.PostURL), mailFont, esc(cta))
	}

	fmt.Fprintf(&b, `
<tr><td style="padding:16px 28px 24px;border-top:1px solid #e3ddd0;">
<p style="margin:0 0 10px;font-family:%s;font-size:12px;line-height:18px;color:#556070;">`+footerBecause+`</p>
<p style="margin:0 0 10px;font-family:%s;font-size:12px;line-height:18px;">
<a href="%s" style="color:#0f766e;text-decoration:underline;">%s</a>
<span style="color:#e3ddd0;">&nbsp;&nbsp;&middot;&nbsp;&nbsp;</span>
<a href="%s" style="color:#556070;text-decoration:underline;">%s</a>
</p>
<p style="margin:0;font-family:%s;font-size:11px;line-height:17px;color:#556070;">%s</p>
</td></tr>
</table>
<!--[if mso]></td></tr></table><![endif]-->
</td></tr></table>
</body>
</html>
`, mailFont, esc(pubName), mailFont, esc(appURL), esc(openLabel), esc(unsubURL), esc(unsubLabel), mailFont, esc(tagline))
	return b.String()
}
